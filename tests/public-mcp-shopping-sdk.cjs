'use strict';
const assert=require('node:assert/strict');
const {createRequire}=require('node:module');
const path=require('node:path');
const {test}=require('node:test');
const {shoppingAdapter}=require('./fixtures/public-mcp-shopping.cjs');
const sdk=createRequire(path.resolve(process.argv[2]||'.','package.json'));
const {Client,StreamableHTTPClientTransport}=sdk('@modelcontextprotocol/client');

for(const profile of ['default','modern'])test(`official ${profile} MCP client creates isolated carts, sets absolute quantity, and displays official photos`,{timeout:60000},async()=>{
    const adapter=shoppingAdapter();
    const info={name:'scoped-shopping-fixture',version:'1'};
    const client=profile==='default'?new Client(info):new Client(info,{versionNegotiation:{mode:{pin:'2026-07-28'}}});
    const call=(name,args)=>client.callTool({name,arguments:args});
    try{
        await client.connect(new StreamableHTTPClientTransport(new URL('https://cart.example.test/api/mcp'),{fetch:adapter.fetch}));
        const tools=(await client.listTools()).tools;
        const cartTool=tools.find(tool=>tool.name==='create_cart');
        assert.equal(cartTool._meta['in.bapx/access'].scope,'anonymous_cart');
        assert.deepEqual(cartTool._meta.ui.visibility,['model','app']);
        const resource=(await client.readResource({uri:cartTool._meta.ui.resourceUri})).contents[0];
        assert.equal(resource.uri,'ui://bapx/public-shopping.html');
        assert.equal(resource.mimeType,'text/html;profile=mcp-app');
        assert.deepEqual(resource._meta.ui.csp.connectDomains,[]);
        assert.deepEqual(resource._meta.ui.csp.resourceDomains,['https://cart.example.test']);
        const products=(await call('search_public_products',{slugs:['sri-varahi-amman-ring'],limit:1})).structuredContent.products;
        assert.equal(products.length,1);
        assert.equal(products[0].imageUrl,'https://cart.example.test/assets/images/products/varahi-amman-ring-front.webp');
        const created=await call('create_cart',{});
        const token=created.structuredContent.cartToken;
        assert.ok(/^cart_[a-f0-9]{32}\.[a-f0-9]{64}$/.test(token),'Creation returns a bounded anonymous capability');
        assert.ok(!JSON.stringify(created.content).includes(token),'Human fallback does not expose capability');
        assert.ok(!JSON.stringify(created._meta).includes(token),'UI metadata does not duplicate capability');
        const args={cartToken:token,slug:'sri-varahi-amman-ring',quantity:2,expectedRevision:0};
        const updated=await call('set_cart_quantity',args);
        assert.equal(updated.structuredContent.revision,1);
        assert.equal(updated.structuredContent.itemCount,2);
        assert.equal(updated.structuredContent.estimatedTotalInr,1001.5);
        assert.equal(updated.structuredContent.cartToken,undefined);
        const replay=await call('set_cart_quantity',args);
        assert.equal(replay.structuredContent.itemCount,2);
        assert.equal(replay.structuredContent.revision,1);
        assert.equal(replay.structuredContent.replayed,true);
        const conflict=await call('set_cart_quantity',{...args,quantity:3});
        assert.equal(conflict.isError,true);
        assert.equal(conflict._meta['in.bapx/shoppingError'].code,'cart_conflict');
        assert.ok(!JSON.stringify(conflict).includes(token));
        const second=await call('create_cart',{});
        assert.equal(second.structuredContent.itemCount,0);
        assert.ok(second.structuredContent.cartToken!==token,'Two unrelated carts stay separate');
        const invalid=await call('set_cart_quantity',{...args,cartToken:second.structuredContent.cartToken,expectedRevision:1});
        assert.equal(invalid.isError,true);
        assert.equal((await call('get_cart',{cartToken:second.structuredContent.cartToken})).structuredContent.itemCount,0);
        assert.equal((await call('create_cart',{role:'admin'})).isError,true);
        await assert.rejects(call('paid_sales_summary',{}));
        adapter.hide('sri-varahi-amman-ring');
        const unavailable=await call('get_cart',{cartToken:token});
        assert.equal(unavailable.structuredContent.items.length,0);
        assert.deepEqual(unavailable.structuredContent.unavailableSlugs,['sri-varahi-amman-ring']);
        assert.equal(unavailable.structuredContent.estimatedTotalInr,null);
        const removed=await call('set_cart_quantity',{...args,quantity:0,expectedRevision:1});
        assert.equal(removed.structuredContent.itemCount,0);
        adapter.advance(86400);
        const expired=await call('get_cart',{cartToken:token});
        assert.equal(expired.isError,true);assert.equal(expired._meta['in.bapx/shoppingError'].code,'cart_expired');
        assert.ok(!adapter.operations.some(value=>/order|payment|reserve|claim_checkout/.test(value)),'No order, payment, reservation or browser claim executed');
        assert.equal(adapter.calls[0].method,profile==='default'?'initialize':'server/discover');
    }finally{await client.close();}
});

for(const profile of ['default','modern'])test(`official ${profile} client reviews inline checkout, reuses payment attempt and verifies saved order`,{timeout:120000},async()=>{
    const adapter=shoppingAdapter();
    const info={name:'anonymous-checkout-sdk-fixture',version:'1'};
    const client=profile==='default'?new Client(info):new Client(info,{versionNegotiation:{mode:{pin:'2026-07-28'}}});
    const call=(name,args)=>client.callTool({name,arguments:args});
    try{
        await client.connect(new StreamableHTTPClientTransport(new URL('https://cart.example.test/api/mcp'),{fetch:adapter.fetch}));
        const tools=(await client.listTools()).tools;
        assert.deepEqual(tools.map(tool=>tool.name),['search_public_products','search_public_articles','get_public_contact','list_public_services',
            'create_cart','get_cart','set_cart_quantity','review_checkout','prepare_checkout_payment','get_checkout_status']);
        assert.ok(tools.every(tool=>!Object.hasOwn(tool.inputSchema.properties,'operation')),'No generic operation selector is model-callable');
        assert.equal(tools.find(tool=>tool.name==='review_checkout').annotations.idempotentHint,false,'Expired quote renewal must not claim strict idempotence');
        const statusTool=tools.find(tool=>tool.name==='get_checkout_status');
        assert.equal(statusTool.annotations.readOnlyHint,false,'Status may reconcile a verified order');
        const resource=(await client.readResource({uri:statusTool._meta.ui.resourceUri})).contents[0];
        assert.ok(resource.text.includes('window.BapxCheckout')&&resource.text.includes('Review checkout'));
        assert.deepEqual(resource._meta.ui.csp.connectDomains,[]);assert.deepEqual(resource._meta.ui.csp.frameDomains,[]);
        assert.ok(!/<script[^>]+src=/i.test(resource.text),'No external provider/UI script is embedded');
        const created=(await call('create_cart',{})).structuredContent;
        const token=created.cartToken;
        await call('set_cart_quantity',{cartToken:token,slug:'sri-varahi-amman-ring',quantity:1,expectedRevision:0});
        const delivery={name:'Synthetic SDK Shopper',email:'sdk-shopper@example.test',phone:'9876543210',
            address:'12 Synthetic SDK Street',city:'Chennai',pincode:'600001',state:'Tamil Nadu',gstin:''};
        const review=await call('review_checkout',{cartToken:token,expectedRevision:1,delivery});
        assert.equal(review.structuredContent.stage,'review_ready');assert.equal(review.structuredContent.cartRevision,2);
        assert.equal(review.structuredContent.totals.totalPaise,50075);assert.equal(review.structuredContent.totals.shippingPaise,0);
        assert.equal(review._meta['in.bapx/shoppingView'],'review');
        for(const privateValue of [token,delivery.name,delivery.email,delivery.phone,delivery.address,delivery.pincode])assert.ok(!JSON.stringify(review).includes(privateValue));
        assert.equal(adapter.state.gatewayCalls.length,0,'Review cannot contact the payment provider');
        const args={cartToken:token,expectedRevision:2,quoteId:review.structuredContent.quote.id,confirm:true};
        const invalid=await call('prepare_checkout_payment',{...args,confirm:false});assert.equal(invalid.isError,true);
        assert.equal(Object.keys(adapter.state.attempts).length,0);
        const prepared=await call('prepare_checkout_payment',args);
        const payment=prepared.structuredContent;
        assert.equal(payment.stage,'payment_ready');assert.equal(payment.amountPaise,50075);assert.equal(payment.mode,'test');
        assert.match(payment.paymentUrl,/^https:\/\/cart\.example\.test\/checkout\/payment\?ticket=pay_[a-f0-9]{32}\.[a-f0-9]{64}$/);
        assert.ok(!JSON.stringify(prepared.content).includes(payment.paymentToken));assert.ok(!JSON.stringify(prepared._meta).includes(payment.paymentToken));
        const replay=await call('prepare_checkout_payment',args);
        assert.equal(replay.structuredContent.paymentToken,payment.paymentToken);assert.equal(replay.structuredContent.attemptId,payment.attemptId);
        assert.equal(adapter.state.gatewayCalls.filter(item=>item.operation==='create_link').length,1);
        const recovered=(await call('get_cart',{cartToken:token})).structuredContent;
        assert.equal(recovered.status,'checkout_locked');assert.equal(recovered.checkout.paymentToken,payment.paymentToken);
        let status=(await call('get_checkout_status',{paymentToken:payment.paymentToken})).structuredContent;
        assert.equal(status.paymentStatus,'pending');assert.equal(status.orderStatus,'not_created');
        adapter.advance(31);adapter.markPaid(payment.attemptId);adapter.configure({failPersist:true});
        status=(await call('get_checkout_status',{paymentToken:payment.paymentToken})).structuredContent;
        assert.equal(status.paymentStatus,'captured');assert.equal(status.orderStatus,'save_pending');assert.equal(status.orderReference,undefined);
        adapter.advance(31);adapter.configure({failPersist:false});
        const saved=await call('get_checkout_status',{paymentToken:payment.paymentToken});status=saved.structuredContent;
        assert.equal(status.paymentStatus,'captured');assert.equal(status.orderStatus,'saved');assert.ok(status.orderReference);
        assert.equal(Object.keys(adapter.state.orders).length,1);assert.equal(saved._meta['in.bapx/shoppingView'],'status');
        for(const privateValue of [token,payment.paymentToken,delivery.email,delivery.address,'synthetic-private@provider'])assert.ok(!JSON.stringify(saved).includes(privateValue));
        const repeated=await call('get_checkout_status',{paymentToken:payment.paymentToken});assert.equal(repeated.structuredContent.orderReference,status.orderReference);
        assert.equal(Object.keys(adapter.state.orders).length,1);
        adapter.advance(604800);assert.equal((await call('get_checkout_status',{paymentToken:payment.paymentToken})).isError,true);
        await assert.rejects(call('shopping_cart',{operation:'create'}));await assert.rejects(call('prepare_checkout',{cartToken:token,expectedRevision:2}));
    }finally{await client.close();}
});
